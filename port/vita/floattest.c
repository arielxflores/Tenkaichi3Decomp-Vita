/* PC program: prints the sums of the exact float model's results over the self-test's operand stream, as the
   header port/vita/vita_float.c includes on the Vita (build.py compiles and runs this; see Vita_FloatSelfTest).
   Built from the same sources as the game's arithmetic: port/src/softfloat_ps2.c and src/port/vu0_a.c. */
#include <stdio.h>
#define FLOATTEST_HOST 1
#include "vita_float.c"

uint32_t Host_DivNearest(uint32_t a, uint32_t b) { (void)a; (void)b; return 0; } /* fast model only: not run here */
void Port_SeamExact(uint32_t x, uint32_t y, uint32_t z, uint32_t fx, uint32_t fy) { (void)x; (void)y; (void)z; (void)fx; (void)fy; } /* (the renderer's: not here) */

int main(void) {
    int op;

    printf("/* generated by port/vita/build.py (floattest.c): the exact float model's sums on the PC */\n");
    printf("static const uint32_t kExpected[TEST_OPS] = {");
    for (op = 0; op < TEST_OPS; op++) {
        printf("%s0x%08Xu", op ? ", " : "", Vita_FloatSum(op));
    }
    printf("};\n");
    return 0;
}
